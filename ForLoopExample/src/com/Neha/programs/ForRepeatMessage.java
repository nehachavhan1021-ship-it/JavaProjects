package com.Neha.programs;

public class ForRepeatMessage {
public static void main (String args[]) {
	for (int i=1;i<=5;i++)
		System.out.println("Good Morning Neha");
	System.out.println();
	for(int i=10;i>=1;i--)
		System.out.println(i+" thanks");
	for(int i=1;i<=25;i+=3)
		System.out.println(i);
	
}
}
